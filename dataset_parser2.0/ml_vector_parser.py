@dataclass
class Patch:
    id: int
    row: int
    col: int
    llx: int
    lly: int
    urx: int
    ury: int

    @property
    def area(self) -> int:
        return max(0, self.urx - self.llx) * max(0, self.ury - self.lly)

    def clip_bbox(self, bbox: tuple[int, int, int, int]) -> tuple[int, int, int, int] | None:
        llx = max(self.llx, bbox[0])
        lly = max(self.lly, bbox[1])
        urx = min(self.urx, bbox[2])
        ury = min(self.ury, bbox[3])
        if llx >= urx or lly >= ury:
            return None
        return (llx, lly, urx, ury)


class PatchIndex:
    def __init__(self, design: DefDesign, patch_size_dbu: int = 3330):
        llx, lly, urx, ury = design.diearea
        self.llx = llx
        self.lly = lly
        self.urx = urx
        self.ury = ury
        self.width = max(1, patch_size_dbu)
        self.height = max(1, patch_size_dbu)
        self.cols = max(1, math.ceil((urx - llx) / self.width))
        self.rows = max(1, math.ceil((ury - lly) / self.height))
        self.patches: list[Patch] = []
        for row in range(self.rows):
            for col in range(self.cols):
                pid = row * self.cols + col
                p_llx = llx + col * self.width
                p_lly = lly + row * self.height
                self.patches.append(
                    Patch(pid, row, col, p_llx, p_lly, min(urx, p_llx + self.width), min(ury, p_lly + self.height))
                )
        self.by_id = {patch.id: patch for patch in self.patches}

    def row(self, y: int) -> int:
        return max(0, min(self.rows - 1, (y - self.lly) // self.height))

    def col(self, x: int) -> int:
        return max(0, min(self.cols - 1, (x - self.llx) // self.width))

    def patch_id(self, x: int, y: int) -> int:
        return self.row(y) * self.cols + self.col(x)

    def patches_for_segment(self, seg: Segment) -> list[int]:
        bbox = (min(seg.x1, seg.x2), min(seg.y1, seg.y2), max(seg.x1, seg.x2), max(seg.y1, seg.y2))
        ids = self.patches_for_bbox(bbox)
        return ids or [self.patch_id(seg.x1, seg.y1)]

    def patches_for_bbox(self, bbox: tuple[int, int, int, int]) -> list[int]:
        col0 = self.col(bbox[0])
        col1 = self.col(bbox[2])
        row0 = self.row(bbox[1])
        row1 = self.row(bbox[3])
        ids = []
        for row in range(row0, row1 + 1):
            for col in range(col0, col1 + 1):
                ids.append(row * self.cols + col)
        return ids

    def wire_density(self, seg: Segment) -> float:
        patch = self.by_id[self.patch_id(seg.x1, seg.y1)]
        return seg.length / patch.area if patch.area else 0


def collect_lefs(platform_dir: Path) -> list[Path]:
    lef_dir = platform_dir / "lef"
    if not lef_dir.exists():
        return []
    preferred = [
        lef_dir / "NangateOpenCellLibrary.tech.lef",
        lef_dir / "NangateOpenCellLibrary.macro.mod.lef",
        lef_dir / "NangateOpenCellLibrary.macro.lef",
    ]
    paths = [path for path in preferred if path.exists()]
    for path in sorted(lef_dir.glob("*.lef")):
        if path not in paths:
            paths.append(path)
    return paths


def collect_libs(
    flow_root: Path,
    platform: str,
    design: str,
    variant: str,
    platform_dir: Path,
    objects_dir: Path | None = None,
) -> list[Path]:
    object_lib_dir = (
        (objects_dir / "lib")
        if objects_dir
        else flow_root / "flow" / "objects" / platform / design / variant / "lib"
    )
    if object_lib_dir.exists():
        object_libs = sorted(object_lib_dir.glob("*.lib"))
        if object_libs:
            return object_libs
    lib_dir = platform_dir / "lib"
    return sorted(lib_dir.rglob("*.lib")) if lib_dir.exists() else []


def ensure_from_odb(odb_path: Path, out_path: Path, script: Path, openroad_bin: str) -> Path:
    if out_path.exists():
        return out_path
    out_path.parent.mkdir(parents=True, exist_ok=True)
    env = os.environ.copy()
    env["ODB_FILE"] = str(odb_path)
    env["DEF_FILE"] = str(out_path)
    env["VERILOG_FILE"] = str(out_path)
    subprocess.run(
        [openroad_bin, str(script)],
        check=True,
        env=env,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
    )
    return out_path


def build_stage(args: argparse.Namespace, stage: str, lef: LefParser, liberty: LibertyParser) -> None:
    flow_root = Path(args.flow_root).resolve()
    platform_dir = flow_root / "flow" / "platforms" / args.platform
    results_dir = (
        Path(args.results_dir).resolve()
        if args.results_dir
        else flow_root / "flow" / "results" / args.platform / args.design / args.variant
    )
    scripts_dir = flow_root / "flow" / "scripts"
    cache_root = (
        Path(args.cache_root).resolve() if args.cache_root else flow_root / ".ml_vector_cache" / args.platform
    )
    cache_dir = cache_root / args.design / args.variant
    if stage == "place":
        stage_odb = results_dir / "3_place.odb"
        def_path = results_dir / "3_place.def"
        verilog_path = results_dir / "3_place.v"
        if not def_path.exists():
            def_path = ensure_from_odb(stage_odb, cache_dir / "3_place.def", scripts_dir / "write_def.tcl", args.openroad)
        if not verilog_path.exists():
            verilog_path = ensure_from_odb(
                stage_odb, cache_dir / "3_place.v", scripts_dir / "write_verilog.tcl", args.openroad
            )
        spef_path: Path | None = None
    elif stage == "cts":
        stage_odb = results_dir / "4_cts.odb"
        def_path = results_dir / "4_cts.def"
        verilog_path = results_dir / "4_cts.v"
        if not def_path.exists():
            def_path = ensure_from_odb(stage_odb, cache_dir / "4_cts.def", scripts_dir / "write_def.tcl", args.openroad)
        if not verilog_path.exists():
            verilog_path = ensure_from_odb(
                stage_odb, cache_dir / "4_cts.v", scripts_dir / "write_verilog.tcl", args.openroad
            )
        spef_path: Path | None = None
    else:
        def_path = results_dir / "6_final.def"
        verilog_path = results_dir / "6_final.v"
        spef_path = results_dir / "6_final.spef"
        if not def_path.exists():
            def_path = ensure_from_odb(
                results_dir / "5_route.odb", cache_dir / "5_route.def", scripts_dir / "write_def.tcl", args.openroad
            )
        if not verilog_path.exists():
            verilog_path = ensure_from_odb(
                results_dir / "5_route.odb", cache_dir / "5_route.v", scripts_dir / "write_verilog.tcl", args.openroad
            )
    ports = parse_verilog_ports(verilog_path)
    design = DefParser(def_path, lef, liberty, ports, default_dbu=args.dbu).parse()
    caps, ress = parse_spef(spef_path) if spef_path is not None else ({}, {})
    for net in design.nets:
        net.capacitance = caps.get(net.name, 0)
        net.resistance = ress.get(net.name, 0)
        net.has_spef = net.name in caps or net.name in ress
    scenario = args.scenario or f"{args.variant}_default"
    output_design = args.dataset_design or dataset_design_name(args.design)
    vectors_dir = (
        Path(args.out).resolve()
        / output_design
        / stage
        / "vectors"
        / f"{output_design}_{stage}_vectors"
        / "vectors"
        / scenario
    )
    reports_dir = (
        Path(args.reports_dir).resolve()
        if args.reports_dir
        else flow_root / "flow" / "reports" / args.platform / args.design / args.variant / "ml_reports"
    )
    report_data = (
        load_ml_reports(reports_dir, stage, args.platform, design.dbu)
        if reports_dir.exists()
        else ReportData(stage=stage)
    )
    # Record which stages this dataset run was configured to parse, so a vector
    # directory always states the switch it was produced under.
    report_data.design_info["parsed_stages"] = list(getattr(args, "stages_enabled", [stage]))
    scenario_params: dict[str, Any] | None = None
    if getattr(args, "scenario_params", ""):
        try:
            scenario_params = json.loads(args.scenario_params)
        except json.JSONDecodeError:
            scenario_params = None
    setrc_ratios = parse_setrc_ratios(platform_dir)
    DatasetWriter(
        design,
        lef,
        liberty,
        vectors_dir,
        report_data,
        patch_size_dbu=args.patch_size_dbu,
        setrc_ratios=setrc_ratios,
    ).write(scenario_params=scenario_params)


STAGE_NAMES = ("place", "cts", "route")

# Legacy --stage values, kept so existing callers (sweep scripts, Makefiles)
# keep working unchanged.
STAGE_PRESETS = {
    "place": ["place"],
    "cts": ["cts"],
    "route": ["route"],
    "both": ["place", "route"],
    "all": ["place", "cts", "route"],
}

DEFAULT_STAGE_CONFIG = Path(__file__).resolve().parent / "stage_config.json"


def load_stage_config(path: Path | None) -> dict[str, bool] | None:
    """Read the three-stage switch file: {"place": bool, "cts": bool, "route": bool}."""
    if path is None or not path.exists():
        return None
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise SystemExit(f"cannot read stage config {path}: {exc}")
    payload = payload.get("stages", payload) if isinstance(payload, dict) else payload
    if not isinstance(payload, dict):
        raise SystemExit(f"stage config {path} must be an object with place/cts/route booleans")
    unknown = sorted(set(payload) - set(STAGE_NAMES))
    if unknown:
        raise SystemExit(f"stage config {path} has unknown keys: {unknown}")
    return {name: bool(payload.get(name, False)) for name in STAGE_NAMES}


def resolve_stages(args: argparse.Namespace) -> list[str]:
    """Resolve the stage switch: CLI flags > --stages > --stage > config file > default.

    With no switch anywhere the built-in default is the historical behaviour
    (place + route); the shipped stage_config.json turns all three stages on,
    and any of the flags above overrides it.
    """
    enabled: dict[str, bool] = {name: name in ("place", "route") for name in STAGE_NAMES}
    if args.stage_config:
        config_path: Path | None = Path(args.stage_config).resolve()
        if not config_path.exists():
            raise SystemExit(f"--stage-config {config_path} does not exist")
    else:
        config_path = DEFAULT_STAGE_CONFIG if DEFAULT_STAGE_CONFIG.exists() else None
    config = load_stage_config(config_path)
    if config is not None:
        enabled = config
    if args.stage:
        enabled = {name: name in STAGE_PRESETS[args.stage] for name in STAGE_NAMES}
    if args.stages:
        requested = [s.strip().lower() for s in args.stages.split(",") if s.strip()]
        unknown = sorted(set(requested) - set(STAGE_NAMES))
        if unknown:
            raise SystemExit(f"--stages has unknown entries: {unknown} (valid: {list(STAGE_NAMES)})")
        enabled = {name: name in requested for name in STAGE_NAMES}
    for name in STAGE_NAMES:
        flag = getattr(args, name)
        if flag is not None:
            enabled[name] = bool(flag)
    selected = [name for name in STAGE_NAMES if enabled[name]]
    if not selected:
        raise SystemExit("no stage enabled: turn on at least one of place/cts/route")
    return selected


def detect_dbu(results_dir: Path, platform: str) -> int:
    """DEF database units of the platform, read from whichever stage DEF exists."""
    for name in ("6_final.def", "5_route.def", "4_cts.def", "3_place.def"):
        path = results_dir / name
        if path.exists():
            match = re.search(r"UNITS\s+DISTANCE\s+MICRONS\s+(\d+)\s*;", read_text(path))
            if match:
                return int(match.group(1))
    return 1000 if platform == "asap7" else 2000


def main() -> None:
    parser = argparse.ArgumentParser(description="Parse ORFS results into gcd-style ML vector datasets.")
    parser.add_argument("--flow-root", default="/home/lyh/OpenROAD-flow-scripts")
    parser.add_argument("--platform", default="nangate45")
    parser.add_argument("--design", required=True)
    parser.add_argument("--variant", default="base")
    parser.add_argument("--dataset-design", default="", help="Output dataset design name. Defaults to normalized --design.")
