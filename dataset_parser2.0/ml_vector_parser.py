"""Build ML vector datasets from OpenROAD-flow-scripts results.

The output layout intentionally mirrors the existing hand-curated datasets:

  <out>/<design>/
    place/vectors/<design>_place_vectors/vectors/<scenario>/...
    cts/vectors/<design>_cts_vectors/vectors/<scenario>/...
    route/vectors/<design>_route_vectors/vectors/<scenario>/...

Strict stage isolation (CTS -> route timing prediction):
  - Each stage parses DEF/Verilog from that stage's own checkpoint only
    (3_place.* / 4_cts.* / 6_final.*).
  - Timing/slew/cap for place/cts come from the stage's placement-based
    parasitic estimation dump (<stage>_net_timing.csv / <stage>_pin_timing.csv
    / <stage>_net_cap.csv) - generated by generate_ml_reports.py on the
    stage's own ODB with `estimate_parasitics -placement`. NO global-routing
    or SPEF information is consumed for pre-routing stages (leakage guard).
  - route stage is the label side: SPEF parasitics + post-route reports.
  - Missing values are written as null, never fake zeros.
"""

