# Every JSON artefact is written zstd-compressed, to `<name>.json.zst`. The
# per-file layout was ~200 GB of pretty-printed JSON for the 61-run nangate45
# sweep, which fits in neither this volume (34 GB free) nor the filesystem's
# inode table, so compression is not optional here. zstd is streamed straight
# into the output file, so the uncompressed form is never materialised.
ZSTD_LEVEL = 3
ZSTD_SUFFIX = ".zst"

# Chunked records (patches, nets, wire paths) are packed into JSONL instead of
# one file each: the per-file layout was ~60M patch files alone, far past the
# ~8M inodes the volume holds. Chunk C holds CHUNK_SIZE consecutive records in
# id order, so record R is line R % CHUNK_SIZE of chunk R // CHUNK_SIZE.
JSONL_CHUNK_SIZE = 10_000
PATCH_DIR = "patchs"
NET_DIR = "nets"
WIRE_PATH_DIR = "wire_paths"


def zstd_path(path: Path) -> Path:
    """Path of the compressed form of `path`."""
    return path.with_name(path.name + ZSTD_SUFFIX)


def open_text_read(path: Path) -> IO[str]:
    """Open `path` for text reading, transparently accepting `.zst`.

    Uncompressed files are still read, so a directory written before the
    compression switch keeps working.
    """
    compressed = zstd_path(path)
    if compressed.exists():
        return zstd.open(compressed, "rt", encoding="utf-8")
    return path.open(encoding="utf-8")


def read_json(path: Path) -> Any:
    with open_text_read(path) as f:
        return json.load(f)


def write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with zstd.open(
        zstd_path(path), "wt", encoding="utf-8", cctx=zstd.ZstdCompressor(level=ZSTD_LEVEL)
    ) as f:
        json.dump(data, f, indent=2)
        f.write("\n")


class JsonlChunkWriter:
    """Stream records into `chunk_XXXXX.jsonl.zst` files, CHUNK_SIZE per chunk.

    Records are machine-read only, so they use compact separators. Chunks are
    opened lazily and closed when the next one starts, which keeps exactly one
    stream (and one 128 KB zstd window) live regardless of record count.
    """

    def __init__(self, vectors_dir: Path, subdir: str, chunk_size: int = JSONL_CHUNK_SIZE) -> None:
        self.dir = vectors_dir / subdir
        self.dir.mkdir(parents=True, exist_ok=True)
        self.chunk_size = chunk_size
        self.count = 0
        self._chunk = -1
        self._file: IO[str] | None = None

    def write(self, record: Any) -> None:
        want = self.count // self.chunk_size
        if want != self._chunk:
            if self._file is not None:
                self._file.close()
            self._file = zstd.open(
                zstd_path(self.dir / f"chunk_{want:05d}.jsonl"),
                "wt",
                encoding="utf-8",
                cctx=zstd.ZstdCompressor(level=ZSTD_LEVEL),
            )
            self._chunk = want
        self._file.write(json.dumps(record, separators=(",", ":")) + "\n")
        self.count += 1

    def close(self) -> int:
        if self._file is not None:
            self._file.close()
            self._file = None
        return self.count

    def write_index(self, **extra: Any) -> None:
        write_json(
            self.dir / "index.json",
            {
                "format": "jsonl",
                "compression": f"zstd level {ZSTD_LEVEL}",
                "chunk_size": self.chunk_size,
                "count": self.count,
                "num_chunks": self._chunk + 1 if self._chunk >= 0 else 0,
                "index": f"记录 id R -> chunk_{{R // chunk_size}}.jsonl.zst 第 R % chunk_size 行",
                **extra,
            },
        )


def iter_jsonl(
    vectors_dir: Path, subdir: str, chunk_size: int = JSONL_CHUNK_SIZE
) -> Iterator[tuple[int, Any]]:
    """Yield (record_id, record) for every record of `subdir`, in id order."""
    meta = read_json(vectors_dir / subdir / "index.json")
    chunk_size = meta.get("chunk_size", chunk_size)
    for chunk in range(meta["num_chunks"]):
        path = vectors_dir / subdir / f"chunk_{chunk:05d}.jsonl"
        with open_text_read(path) as f:
            for line_no, line in enumerate(f):
                if line.strip():
                    yield chunk * chunk_size + line_no, json.loads(line)


def load_jsonl_record(vectors_dir: Path, subdir: str, record_id: int) -> Any:
    """Read one record without walking the rest of the chunked directory.

    The chunk size comes from the directory's own index rather than the
    module constant, so a directory written with a different chunk size is
    still addressed correctly.
    """
    chunk_size = read_json(vectors_dir / subdir / "index.json").get("chunk_size", JSONL_CHUNK_SIZE)
    want = record_id % chunk_size
    path = vectors_dir / subdir / f"chunk_{record_id // chunk_size:05d}.jsonl"
    with open_text_read(path) as f:
        for line_no, line in enumerate(f):
            if line_no == want:
                return json.loads(line)
    raise KeyError(f"{subdir} 记录 {record_id} 不在 {path}")


def iter_patches(vectors_dir: Path) -> Iterator[tuple[int, dict[str, Any]]]:
    """Yield (patch_id, record) for every patch, in patch-id order."""
    return iter_jsonl(vectors_dir, PATCH_DIR)


def load_patch(vectors_dir: Path, patch_id: int) -> dict[str, Any]:
    """Read one patch record without walking the rest of the grid."""
    return load_jsonl_record(vectors_dir, PATCH_DIR, patch_id)


def iter_nets(vectors_dir: Path) -> Iterator[tuple[int, dict[str, Any]]]:
    """Yield (net_id, record) for every net, in net-id order."""
    return iter_jsonl(vectors_dir, NET_DIR)


def load_net(vectors_dir: Path, net_id: int) -> dict[str, Any]:
    """Read one net record without walking the rest of the directory."""
    return load_jsonl_record(vectors_dir, NET_DIR, net_id)


def iter_wire_paths(vectors_dir: Path) -> Iterator[tuple[int, Any]]:
    """Yield (path_id, record) for every wire path, in path-id order."""
    return iter_jsonl(vectors_dir, WIRE_PATH_DIR)


def load_wire_path(vectors_dir: Path, path_id: int) -> Any:
    """Read one wire-path record without walking the rest of the directory."""
    return load_jsonl_record(vectors_dir, WIRE_PATH_DIR, path_id)


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="ignore")


def strip_def_comments(text: str) -> str:
    return "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("#"))


def normalize_design_name(name: str) -> str:
    return name.replace("\\[", "[").replace("\\]", "]").replace("\\", "")


def dataset_design_name(orfs_design: str) -> str:
    """Map ORFS result nicknames to the stable dataset design name."""
    name = orfs_design
    if name.startswith("bench_"):
        name = name[len("bench_") :]
    for suffix in (
        "_fastclk_bad_m3",
        "_fastclk_bad",
        "_grt_repair_off70",
        "_dense70",
    ):
        if name.endswith(suffix):
            name = name[: -len(suffix)]
    return name


def dbu_float_to_int(value: str, dbu: int) -> int:
    return int(round(float(value) * dbu))


def is_signal_instance(name: str, cell: str) -> bool:
    upper_name = name.upper()
    upper_cell = cell.upper()
    return not any(upper_name.startswith(p) for p in SKIP_INSTANCE_PREFIXES) and not any(
        upper_cell.startswith(p) for p in SKIP_CELL_PREFIXES
    )


@dataclass
class Cell:
    id: int
    name: str
    width: int
    height: int
    pins: dict[str, str] = field(default_factory=dict)


@dataclass
class Instance:
    id: int
    name: str
    cell: str
    cell_id: int
    llx: int
    lly: int
    width: int
    height: int
    status: str = "PLACED"
    orient: str = "N"

    @property
    def cx(self) -> int:
        return self.llx + self.width // 2

    @property
    def cy(self) -> int:
        return self.lly + self.height // 2

    @property
    def urx(self) -> int:
        return self.llx + self.width

    @property
    def ury(self) -> int:
        return self.lly + self.height


@dataclass
class Port:
    name: str
    direction: str = "INOUT"
    x: int = 0
    y: int = 0


@dataclass
class Segment:
    x1: int
    y1: int
    layer1: int
    x2: int
    y2: int
    layer2: int
    via: str | None = None

    @property
    def length(self) -> int:
        if self.layer1 != self.layer2:
            return 0
        return abs(self.x1 - self.x2) + abs(self.y1 - self.y2)


