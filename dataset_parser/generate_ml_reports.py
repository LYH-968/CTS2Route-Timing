def preroute_report_tcl(
    flow_root: Path,
    platform: str,
    design: str,
    variant: str,
    group_path_count: int,
    endpoint_path_count: int,
    stage_odb: str,
    stage_sdc: str,
    json_dir_name: str,
    rpt_name: str,
    summary_name: str,
    net_timing_prefix: str,
    results_dir: Path | None = None,
    reports_dir: Path | None = None,
    objects_dir: Path | None = None,
) -> str:
    results_dir = results_dir or flow_root / "flow" / "results" / platform / design / variant
    reports_dir = reports_dir or flow_root / "flow" / "reports" / platform / design / variant / "ml_reports"
    platform_dir = flow_root / "flow" / "platforms" / platform
    lib_file = liberty_file(flow_root, platform, design, variant, objects_dir)
    setrc = platform_dir / "setRC.tcl"
    # NOTE: pre-routing stages (place/cts) must NOT use any routing information.
    # Parasitics come from `estimate_parasitics -placement` (Steiner-length-based
    # estimation, the same command ORFS cts.tcl itself uses post-CTS). No
    # global_route, no estimate_parasitics -global_routing, no SPEF, no GRT
    # congestion here - otherwise this would leak future routing information
    # into the pre-routing stage prediction input.
    return f"""
set results_dir {tcl_quote(results_dir)}
set out_dir {tcl_quote(reports_dir)}
file mkdir $out_dir

{dump_net_timing_proc()}
read_liberty {tcl_quote(lib_file)}
read_db $results_dir/{stage_odb}
read_sdc $results_dir/{stage_sdc}

if {{[file exists {setrc}]}} {{
  source {tcl_quote(setrc)}
}}

# Pre-routing stage: clock state restored, then placement-based parasitic
# estimation (Steiner wire model from cell/pin locations only).
if {{[llength [all_clocks]] > 0}} {{
  set_propagated_clock [all_clocks]
}}
estimate_parasitics -placement

{endpoint_report_tcl(json_dir_name, rpt_name, summary_name)}
write_all_endpoint_timing_reports $out_dir
dump_net_timing $out_dir {net_timing_prefix}
dump_design_info $out_dir {net_timing_prefix}
exit
"""


def has_required_files(
    flow_root: Path, platform: str, design: str, variant: str, stage: str, results_dir: Path | None = None
) -> bool:
    results_dir = results_dir or flow_root / "flow" / "results" / platform / design / variant
    if stage == "final":
        return (results_dir / "6_final.odb").exists()
    if stage == "place":
        return (results_dir / "3_place.odb").exists() and (results_dir / "3_place.sdc").exists()
    return (results_dir / "4_cts.odb").exists() and (results_dir / "4_cts.sdc").exists()


def combine_endpoint_reports(reports_dir: Path, json_dir_name: str, output_json_name: str, summary_name: str) -> None:
    json_dir = reports_dir / json_dir_name
    endpoint_file = reports_dir / f"{json_dir_name}_endpoints.txt"
    if not json_dir.exists():
        return
    checks = []
    seen = set()
    for path in sorted(json_dir.glob("endpoint_*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8", errors="ignore"))
        except json.JSONDecodeError:
            continue
        for check in data.get("checks", []):
            key = (
                check.get("path_type"),
                check.get("startpoint"),
                check.get("endpoint"),
                check.get("slack"),
                check.get("arrival_time"),
            )
            if key in seen:
                continue
            seen.add(key)
            checks.append(check)
    endpoints = []
    if endpoint_file.exists():
        endpoints = [
            line.strip()
            for line in endpoint_file.read_text(encoding="utf-8", errors="ignore").splitlines()
            if line.strip()
        ]
    reported = {check.get("endpoint") for check in checks if check.get("endpoint")}
    missing = sorted(set(endpoints) - reported)
    for endpoint in missing:
        checks.append(
            {
                "type": "endpoint",
                "path_group": "unconstrained",
                "path_type": "unconstrained",
                "startpoint": "",
                "endpoint": endpoint,
                "source_clock": "",
                "source_path": [],
                "target_clock": "",
                "target_clock_path": [],
                "slack": None,
                "required_time": None,
                "endpoint_has_timing_path": False,
            }
        )
    reported = {check.get("endpoint") for check in checks if check.get("endpoint")}
    (reports_dir / output_json_name).write_text(json.dumps({"checks": checks}, indent=2) + "\n", encoding="utf-8")
    summary = {
        "endpoint_count": len(endpoints),
        "reported_endpoint_count": len(reported),
        "missing_endpoint_count": len(set(endpoints) - reported),
        "no_path_endpoint_count": len(missing),
        "check_count": len(checks),
        "json_dir": json_dir_name,
        "output_json": output_json_name,
    }
    existing = reports_dir / summary_name
    if existing.exists():
        try:
            summary = {**json.loads(existing.read_text(encoding="utf-8", errors="ignore")), **summary}
        except json.JSONDecodeError:
            pass
    existing.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")


def parse_liberty_op_conds(lib_path: Path) -> dict[str, Any]:
    """Parse process/temperature/voltage from the first operating_conditions block."""
    info: dict[str, Any] = {}
    if not lib_path.exists():
        return info
    text = lib_path.read_text(encoding="utf-8", errors="ignore")
    match = re.search(r"\boperating_conditions\s*\(\s*([^)]+)\s*\)\s*\{(.*?)\}", text, re.S)
    if not match:
        return info
    body = match.group(2)
    for key in ("process", "temperature", "voltage"):
        value = re.search(rf"\b{key}\s*:\s*([^;]+);", body)
        if value:
            info[key] = value.group(1).strip().strip('"')
    return info


def wns_tns_from_checks(checks: list[dict[str, Any]]) -> dict[str, float | None]:
    """WNS/TNS for max and min computed from per-endpoint path checks."""
    slacks: dict[str, list[float]] = {"max": [], "min": []}
    for check in checks:
        slack = check.get("slack")
        if slack is None:
            continue
        path_type = str(check.get("path_type", "max"))
        if path_type not in slacks:
            continue
        slacks[path_type].append(float(slack))
    result: dict[str, float | None] = {}
    for key in ("max", "min"):
        values = slacks[key]
        result[f"wns_{key}"] = min(values) if values else None
        result[f"tns_{key}"] = sum(v for v in values if v < 0) if values else None
        result[f"endpoint_count_{key}"] = len(values) if values else None
    return result


def write_stage_design_info(
    reports_dir: Path,
    stage: str,
    platform: str,
    design: str,
    variant: str,
    lib_file: Path,
    combined_report_name: str,
) -> None:
    """Merge Tcl-dumped design info (die/core area, clocks), liberty PVT,
    routing constraints and WNS/TNS into <stage>_design_info.json."""
    prefix = {"place": "place_", "cts": "cts_", "route": "route_"}[stage]
    # Stage-boundary metadata. Pre-routing stages (place/cts) use placement-based
    # parasitic estimation only - no global_route, no SPEF, no GRT congestion.
    stage_meta = {
        "place": {
            "stage_label": "post_place_pre_cts",
            "parasitic_source": "placement_estimation",
            "clock_mode": "propagated",
            "routing_information_used": False,
            "source_checkpoint": "3_place.odb",
        },
        "cts": {
            "stage_label": "post_cts_pre_grt",
            "parasitic_source": "placement_estimation",
            "clock_mode": "propagated",
            "routing_information_used": False,
            "source_checkpoint": "4_cts.odb",
        },
        "route": {
            "stage_label": "post_route",
            "parasitic_source": "extracted_spef",
            "clock_mode": "propagated",
            "routing_information_used": True,
            "source_checkpoint": "6_final.odb",
        },
    }[stage]
    min_layer, min_clk_layer, max_layer = routing_layers(platform)
    info: dict[str, Any] = {
        "design": design,
        "platform": platform,
        "variant": variant,
        "stage": stage,
        "stage_label": stage_meta["stage_label"],
        "parasitic_source": stage_meta["parasitic_source"],
        "clock_mode": stage_meta["clock_mode"],
        "routing_information_used": stage_meta["routing_information_used"],
        "source_checkpoint": stage_meta["source_checkpoint"],
        "liberty_file": str(lib_file),
        "process": None,
        "temperature": None,
        "voltage": None,
        "min_routing_layer": min_layer,
        "min_clk_routing_layer": min_clk_layer,
        "max_routing_layer": max_layer,
        "routing_layer_adjustment": 0.3,
        "die_area_um2": None,
        "core_area_um2": None,
        "clock_periods_s": {},
        "wns_max": None,
        "wns_min": None,
        "tns_max": None,
        "tns_min": None,
    }
    info.update(parse_liberty_op_conds(lib_file))
    csv_path = reports_dir / f"{prefix}design_info.csv"
    if csv_path.exists():
        with csv_path.open("r", encoding="utf-8", errors="ignore", newline="") as f:
            for row in csv.DictReader(f):
                key, value = row.get("key", ""), row.get("value", "")
                if key.startswith("clock_") and key.endswith("_period_s"):
                    try:
                        info["clock_periods_s"][key[len("clock_") : -len("_period_s")]] = float(value)
                    except ValueError:
                        pass
                elif key in ("die_area_um2", "core_area_um2"):
                    try:
                        info[key] = float(value)
                    except ValueError:
                        pass
    combined = reports_dir / combined_report_name
    if combined.exists():
        try:
            checks = json.loads(combined.read_text(encoding="utf-8", errors="ignore")).get("checks", [])
        except json.JSONDecodeError:
            checks = []
        info.update(wns_tns_from_checks(checks))
    (reports_dir / f"{prefix}design_info.json").write_text(json.dumps(info, indent=2) + "\n", encoding="utf-8")


def parse_spef_caps(spef_path: Path) -> dict[str, float]:
    if not spef_path.exists():
        return {}
    text = spef_path.read_text(encoding="utf-8", errors="ignore")
    name_map: dict[str, str] = {}
    in_name_map = False
    for line in text.splitlines():
        if line.startswith("*NAME_MAP"):
            in_name_map = True
            continue
        if in_name_map and line.startswith("*") and not re.match(r"\*\d+\s+", line):
            in_name_map = False
        if in_name_map:
            match = re.match(r"\*(\d+)\s+(.+)", line)
            if match:
                name_map[f"*{match.group(1)}"] = match.group(2).strip()
    caps: dict[str, float] = {}
    for match in re.finditer(r"(?m)^\*D_NET\s+(\S+)\s+([-+eE.\d]+)", text):
        raw_name, cap = match.group(1), float(match.group(2))
        caps[name_map.get(raw_name, raw_name)] = cap
    return caps


def read_clock_period_ps(results_dir: Path) -> float | None:
    path = results_dir / "clock_period.txt"
    if not path.exists():
        return None
    try:
        return float(path.read_text(encoding="utf-8", errors="ignore").strip())
    except ValueError:
        return None


def write_estimated_net_power(
    flow_root: Path,
    platform: str,
    design: str,
    variant: str,
    activity: float,
    results_dir: Path | None = None,
    reports_dir: Path | None = None,
) -> None:
    results_dir = results_dir or flow_root / "flow" / "results" / platform / design / variant
    reports_dir = reports_dir or flow_root / "flow" / "reports" / platform / design / variant / "ml_reports"
    reports_dir.mkdir(parents=True, exist_ok=True)
    caps_pf = parse_spef_caps(results_dir / "6_final.spef")
    period_ps = read_clock_period_ps(results_dir)
    voltage = platform_nominal_voltage(platform)
    out = reports_dir / "net_power.csv"
    lines = ["net,capacitance_pf,activity,voltage_v,frequency_hz,switching_power_w,source"]
    if period_ps and period_ps > 0:
        frequency_hz = 1.0 / (period_ps * 1e-12)
        for net, cap_pf in sorted(caps_pf.items()):
            power = cap_pf * 1e-12 * voltage * voltage * frequency_hz * activity
            lines.append(f"{net},{cap_pf},{activity},{voltage},{frequency_hz},{power},estimated_from_spef_activity")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


