def platform_nominal_voltage(platform: str) -> float:
    if platform == "asap7":
        return 0.77
    return 1.1


def routing_layers(platform: str) -> tuple[str, str, str]:
    if platform == "asap7":
        return "M2", "M4", "M7"
    return "metal2", "metal4", "metal10"


def liberty_file(
    flow_root: Path, platform: str, design: str, variant: str, objects_dir: Path | None = None
) -> Path:
    if objects_dir:
        merged = objects_dir / "lib" / "merged.lib"
        if merged.is_file():
            return merged
        candidates = sorted((objects_dir / "lib").glob("**/*.lib")) + sorted(
            (objects_dir / "lib").glob("**/*.lib.gz")
        )
        if candidates:
            return candidates[0]
    merged = flow_root / "flow" / "objects" / platform / design / variant / "lib" / "merged.lib"
    if merged.is_file():
        return merged
    platform_dir = flow_root / "flow" / "platforms" / platform
    nangate = platform_dir / "lib" / "NangateOpenCellLibrary_typical.lib"
    if nangate.is_file():
        return nangate
    candidates = sorted((platform_dir / "lib").glob("**/*.lib")) + sorted(
        (platform_dir / "lib").glob("**/*.lib.gz")
    )
    if candidates:
        return candidates[0]
    raise FileNotFoundError(f"no Liberty file found for {platform}/{design}/{variant}")


def tcl_quote(path: Path | str) -> str:
    text = str(path)
    return "{" + text.replace("}", "\\}") + "}"


def discover_designs(results_root: Path, variant: str) -> list[str]:
    designs = []
    for child in sorted(results_root.iterdir()):
        if child.is_dir() and (child / variant).is_dir():
            designs.append(child.name)
    return designs


def run_openroad(openroad: str, tcl: str, log: Path) -> bool:
    log.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", suffix=".tcl", delete=False, encoding="utf-8") as f:
        f.write(tcl)
        tcl_path = Path(f.name)
    try:
        proc = subprocess.run(
            [openroad, "-no_init", "-no_splash", str(tcl_path)],
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
        )
        log.write_text(proc.stdout, encoding="utf-8", errors="ignore")
        return proc.returncode == 0
    finally:
        tcl_path.unlink(missing_ok=True)


def report_check_options(group_path_count: int, endpoint_path_count: int) -> str:
    return (
        f"-group_path_count {group_path_count} \\\n"
        f"  -endpoint_path_count {endpoint_path_count} \\\n"
        "  -unique_paths_to_endpoint"
    )


def endpoint_report_tcl(json_dir_name: str, rpt_name: str, summary_name: str) -> str:
    return f"""
proc write_all_endpoint_timing_reports {{out_dir}} {{
  set json_dir "$out_dir/{json_dir_name}"
  file delete -force $json_dir
  file mkdir $json_dir

  set rpt_file "$out_dir/{rpt_name}"
  set fp [open $rpt_file w]
  puts $fp "# Endpoint-complete timing report."
  puts $fp "# Generated by enumerating all_registers -data_pins and all_outputs."
  close $fp

  set endpoint_list "$out_dir/{json_dir_name}_endpoints.txt"
  set efp [open $endpoint_list w]
  array set seen {{}}
  set endpoints {{}}
  foreach endpoint [concat [all_registers -data_pins] [all_outputs]] {{
    set endpoint_name [get_full_name $endpoint]
    if {{![info exists seen($endpoint_name)]}} {{
      set seen($endpoint_name) 1
      lappend endpoints $endpoint
      puts $efp $endpoint_name
    }}
  }}
  close $efp

  set idx 0
  foreach endpoint $endpoints {{
    set endpoint_name [get_full_name $endpoint]
    foreach delay {{max min}} {{
      set json_file "$json_dir/[format {{endpoint_%06d_%s.json}} $idx $delay]"
      set afp [open $rpt_file a]
      puts $afp ""
      puts $afp "=========================================================================="
      puts $afp "endpoint $idx $delay $endpoint_name"
      puts $afp "--------------------------------------------------------------------------"
      close $afp
      catch {{
        report_checks -path_delay $delay -to $endpoint -format full_clock_expanded \\
          -fields {{input_pin slew capacitance net}} -endpoint_path_count 1 >> $rpt_file
      }} rpt_err
      catch {{
        report_checks -path_delay $delay -to $endpoint -format json \\
          -endpoint_path_count 1 > $json_file
      }} json_err
    }}
    incr idx
  }}

  set sfp [open "$out_dir/{summary_name}" w]
  puts $sfp "{{"
  puts $sfp "  \\"endpoint_count\\": [llength $endpoints],"
  puts $sfp "  \\"path_delays\\": [list \\"max\\" \\"min\\"],"
  puts $sfp "  \\"source\\": \\"all_registers -data_pins + all_outputs\\""
  puts $sfp "}}"
  close $sfp
}}
"""


def dump_net_timing_proc() -> str:
    """Tcl proc that dumps per-net-arc timing for ALL signal nets.

    Uses the OpenSTA SWIG Tcl API instead of path-based report_checks so
    every wire edge (driver -> sink) gets its rise/fall x min/max delay
    and slew, including nets driven by top-level input ports and clock
    tree nets. Nets without any timing arc (constant/undriven) still get
    a net_cap row so their capacitance is captured.

    Also writes a per-pin timing file (location, arrival, slack, 4-corner
    slew, required + valid mask) and a design info file (die/core area,
    clock periods).
    """
    return """
proc dump_net_timing {out_dir prefix} {
  set corner [lindex [sta::corners] 0]
  set tp [open "$out_dir/${prefix}net_timing.csv" w]
  puts $tp "driver_pin,sink_pin,net,rf,delay_min_s,delay_max_s,driver_slew_min_s,driver_slew_max_s,sink_slew_min_s,sink_slew_max_s"
  set cp [open "$out_dir/${prefix}net_cap.csv" w]
  puts $cp "net,cap_f,wire_cap_f"
  set pp [open "$out_dir/${prefix}pin_timing.csv" w]
  puts $pp "pin,net,is_driver,x_um,y_um,arrival_min_s,arrival_max_s,slack_min_s,slack_max_s,slew_rise_min_s,slew_rise_max_s,slew_fall_min_s,slew_fall_max_s,req_min_s,req_max_s,req_valid"
  set n_arcs 0
  set n_net_cap 0
  set n_pins 0
  foreach net [get_nets -hier] {
    if {[sta::Net_is_power $net] || [sta::Net_is_ground $net]} { continue }
    set net_name [get_full_name $net]
    # Total cap (wire + pin) and wire-only cap of the stage's parasitic
    # annotation (placement estimation for place/cts, SPEF for route).
    set cap_str ""; set wcap_str ""
    if {![catch { set cap_val [sta::Net_capacitance $net $corner max] } cap_err]} {
      set cap_str $cap_val
    }
    if {![catch { set wcap_val [sta::Net_wire_capacitance $net $corner max] } wcap_err]} {
      set wcap_str $wcap_val
    }
    puts $cp "$net_name,$cap_str,$wcap_str"
    if {$cap_str ne ""} { incr n_net_cap }
    if {[catch { set it [sta::Net_connected_pin_iterator $net] } it_err]} { continue }
    while {[sta::NetConnectedPinIterator_has_next $it]} {
      set pin [sta::NetConnectedPinIterator_next $it]
      set pin_name [get_full_name $pin]
      # Per-pin features: location, arrival, slack.
      set loc ""
      if {![catch { set loc [sta::pin_location $pin] } loc_err]} { } else { set loc "" }
      set xum ""; set yum ""
      if {[llength $loc] >= 2} { set xum [lindex $loc 0]; set yum [lindex $loc 1] }
      foreach v [$pin vertices] {
        set amin ""; set amax ""; set smin ""; set smax ""
        if {![catch { set amax [sta::Vertex_arrival $v max] } ea1]} {
          if {$amax <= -1e29 || $amax >= 1e29} { set amax "" }
        } else { set amax "" }
        if {![catch { set amin [sta::Vertex_arrival $v min] } ea2]} {
          if {$amin <= -1e29 || $amin >= 1e29} { set amin "" }
        } else { set amin "" }
        if {![catch { set smax [sta::Vertex_slack $v max] } es1]} {
          if {$smax <= -1e29 || $smax >= 1e29} { set smax "" }
        } else { set smax "" }
        if {![catch { set smin [sta::Vertex_slack $v min] } es2]} {
          if {$smin <= -1e29 || $smin >= 1e29} { set smin "" }
        } else { set smin "" }
        # Per-pin 4-corner slew and per-pin required times.
        # Required: vertexRequired is per-clock; iterate all clocks x clk_rf and
        # keep the tightest (minimum) valid values. Vertex_requireds_clk returns
        # one value per path analysis point ([min, max] order for single corner).
        set srmin ""; set srmax ""; set sfmin ""; set sfmax ""
        if {![catch { set srmin [sta::Vertex_slew $v rise min] } et1]} {
          if {$srmin <= -1e29 || $srmin >= 1e29} { set srmin "" }
        } else { set srmin "" }
        if {![catch { set srmax [sta::Vertex_slew $v rise max] } et2]} {
          if {$srmax <= -1e29 || $srmax >= 1e29} { set srmax "" }
        } else { set srmax "" }
        if {![catch { set sfmin [sta::Vertex_slew $v fall min] } et3]} {
          if {$sfmin <= -1e29 || $sfmin >= 1e29} { set sfmin "" }
        } else { set sfmin "" }
        if {![catch { set sfmax [sta::Vertex_slew $v fall max] } et4]} {
          if {$sfmax <= -1e29 || $sfmax >= 1e29} { set sfmax "" }
        } else { set sfmax "" }
        set reqmin ""; set reqmax ""; set req_ok 0
        foreach clk [all_clocks] {
          foreach clk_rf {rise fall} {
            foreach rf {rise fall} {
              if {[catch { set reqs [sta::Vertex_requireds_clk $v $rf $clk $clk_rf] } rerr]} { continue }
              set idx 0
              foreach r $reqs {
                if {$r > -1e29 && $r < 1e29} {
                  set target [expr {$idx % 2 == 0 ? "reqmin" : "reqmax"}]
                  if {[set $target] eq "" || $r < [set $target]} { set $target $r }
                  set req_ok 1
                }
                incr idx
              }
            }
          }
        }
        puts $pp "$pin_name,$net_name,[sta::Pin_is_driver $pin],$xum,$yum,$amin,$amax,$smin,$smax,$srmin,$srmax,$sfmin,$sfmax,$reqmin,$reqmax,$req_ok"
        incr n_pins
        if {[catch { set eit [$v in_edge_iterator] } eit_err]} { continue }
        while {[$eit has_next]} {
          set e [$eit next]
          if {[$e role] ne "wire"} { continue }
          set from_v [$e from]
          set driver_pin [$from_v pin]
          set driver_name [get_full_name $driver_pin]
          set sink_name [get_full_name $pin]
          foreach arc [$e timing_arcs] {
            if {[catch { set rf [sta::TimingArc_from_edge_name $arc] } rf_err]} { continue }
            if {[catch { set dmax [$e arc_delay $arc $corner max] } emax]} { continue }
            if {[catch { set dmin [$e arc_delay $arc $corner min] } emin]} { set dmin $dmax }
            if {[catch { set drv_sl_max [sta::Vertex_slew $from_v $rf max] } es1]} { set drv_sl_max "" }
            if {[catch { set drv_sl_min [sta::Vertex_slew $from_v $rf min] } es2]} { set drv_sl_min "" }
            if {[catch { set snk_sl_max [sta::Vertex_slew $v $rf max] } es3]} { set snk_sl_max "" }
            if {[catch { set snk_sl_min [sta::Vertex_slew $v $rf min] } es4]} { set snk_sl_min "" }
            puts $tp "$driver_name,$sink_name,$net_name,$rf,$dmin,$dmax,$drv_sl_min,$drv_sl_max,$snk_sl_min,$snk_sl_max"
            incr n_arcs
          }
        }
        $eit finish
      }
    }
    sta::NetConnectedPinIterator_finish $it
  }
  close $tp
  close $cp
  close $pp
  puts "# dumped $n_arcs net timing arcs, $n_net_cap net caps, $n_pins pin rows"
}

proc dump_design_info {out_dir prefix} {
  set fp [open "$out_dir/${prefix}design_info.csv" w]
  puts $fp "key,value"
  set die [ord::get_die_area]
  set core [ord::get_core_area]
  if {[llength $die] >= 4} {
    set die_area [expr {([lindex $die 2] - [lindex $die 0]) * ([lindex $die 3] - [lindex $die 1])}]
    puts $fp "die_area_um2,$die_area"
  }
  if {[llength $core] >= 4} {
    set core_area [expr {([lindex $core 2] - [lindex $core 0]) * ([lindex $core 3] - [lindex $core 1])}]
    puts $fp "core_area_um2,$core_area"
  }
  foreach clk [all_clocks] {
    if {![catch { set period [sta::Clock_period $clk] } perr]} {
      puts $fp "clock_[get_name $clk]_period_s,$period"
    }
  }
  close $fp
}
"""


def final_report_tcl(
    flow_root: Path,
    platform: str,
    design: str,
    variant: str,
    group_path_count: int,
    endpoint_path_count: int,
    results_dir: Path | None = None,
    reports_dir: Path | None = None,
    objects_dir: Path | None = None,
) -> str:
    results_dir = results_dir or flow_root / "flow" / "results" / platform / design / variant
    reports_dir = reports_dir or flow_root / "flow" / "reports" / platform / design / variant / "ml_reports"
    platform_dir = flow_root / "flow" / "platforms" / platform
    lib_file = liberty_file(flow_root, platform, design, variant, objects_dir)
    setrc = platform_dir / "setRC.tcl"
    voltage = platform_nominal_voltage(platform)
    return f"""
set results_dir {tcl_quote(results_dir)}
set out_dir {tcl_quote(reports_dir)}
file mkdir $out_dir

{dump_net_timing_proc()}
read_liberty {tcl_quote(lib_file)}
read_db $results_dir/6_final.odb

if {{[file exists $results_dir/6_final.sdc]}} {{
  read_sdc $results_dir/6_final.sdc
}} elseif {{[file exists $results_dir/5_route.sdc]}} {{
  read_sdc $results_dir/5_route.sdc
}}

if {{[file exists {setrc}]}} {{
  source {tcl_quote(setrc)}
}}

if {{[file exists $results_dir/6_final.spef]}} {{
  read_spef $results_dir/6_final.spef
}}

catch {{ set_propagated_clock [all_clocks] }}
catch {{ set_power_activity -input -activity 0.1 }}
catch {{ set_power_activity -input_port reset -activity 0 }}

{endpoint_report_tcl("path_report_endpoint_json", "path_report.rpt", "endpoint_report_summary.json")}
write_all_endpoint_timing_reports $out_dir
dump_net_timing $out_dir route_
dump_design_info $out_dir route_

report_checks -unconstrained -format full_clock_expanded \\
  -fields {{input_pin slew capacitance net}} \\
  {report_check_options(group_path_count, endpoint_path_count)} > $out_dir/path_report_unconstrained.rpt

    report_power -digits 6 > $out_dir/power.rpt
    report_power -instances [get_cells *] -digits 6 > $out_dir/instance_power.rpt
    catch {{ check_drc -output_file $out_dir/drc.rpt }} drc_error
    if {{[info exists drc_error] && $drc_error ne ""}} {{
      set fp [open "$out_dir/drc.log" w]
      puts $fp $drc_error
      close $fp
    }}
    catch {{
      set_pdnsim_net_voltage -net VDD -voltage {voltage}
      analyze_power_grid -net VDD -source_type STRAPS \\
        -error_file $out_dir/ir_drop_VDD.rpt \\
        -voltage_file $out_dir/ir_drop_VDD.csv
    }} ir_vdd_error
    if {{[info exists ir_vdd_error] && $ir_vdd_error ne ""}} {{
      set fp [open "$out_dir/ir_drop_VDD.log" w]
      puts $fp $ir_vdd_error
      close $fp
    }}
    catch {{
      set_pdnsim_net_voltage -net VSS -voltage 0.0
      analyze_power_grid -net VSS -source_type STRAPS \\
        -error_file $out_dir/ir_drop_VSS.rpt \\
        -voltage_file $out_dir/ir_drop_VSS.csv
    }} ir_vss_error
    if {{[info exists ir_vss_error] && $ir_vss_error ne ""}} {{
      set fp [open "$out_dir/ir_drop_VSS.log" w]
      puts $fp $ir_vss_error
      close $fp
    }}
    report_wns > $out_dir/wns.rpt
report_tns > $out_dir/tns.rpt
report_design_area > $out_dir/design_area.rpt
exit
"""


