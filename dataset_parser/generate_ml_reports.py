#!/usr/bin/env python3
"""Generate timing, power, and congestion reports for ORFS ML parsing.

Reports are written to:

  flow/reports/<platform>/<design>/<variant>/ml_reports/

The script intentionally uses plain OpenROAD Tcl so it can run on already
completed ORFS result directories without re-entering the full Make flow.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import tempfile
from pathlib import Path


DEFAULT_OPENROAD = "/home/lyh/OpenROAD-flow-scripts/tools/install/OpenROAD/bin/openroad"
DEFAULT_ACTIVITY = 0.1


def platform_nominal_voltage(platform: str) -> float:
    if platform == "asap7":
        return 0.77
    return 1.1


def routing_layers(platform: str) -> tuple[str, str, str]:
    if platform == "asap7":
        return "M2", "M4", "M7"
    return "metal2", "metal4", "metal10"


def liberty_file(flow_root: Path, platform: str, design: str, variant: str, objects_dir: Path | None = None) -> Path:
    if objects_dir:
        merged = objects_dir / "lib" / "merged.lib"
        if merged.is_file():
            return merged
        candidates = sorted((objects_dir / "lib").glob("**/*.lib")) + sorted((objects_dir / "lib").glob("**/*.lib.gz"))
        if candidates:
            return candidates[0]
    merged = flow_root / "flow" / "objects" / platform / design / variant / "lib" / "merged.lib"
    if merged.is_file():
        return merged
    platform_dir = flow_root / "flow" / "platforms" / platform
    nangate = platform_dir / "lib" / "NangateOpenCellLibrary_typical.lib"
    if nangate.is_file():
        return nangate
    candidates = sorted((platform_dir / "lib").glob("**/*.lib")) + sorted((platform_dir / "lib").glob("**/*.lib.gz"))
    if candidates:
        return candidates[0]
    raise FileNotFoundError(f"no Liberty file found for {platform}/{design}/{variant}")


def tcl_quote(path: Path | str) -> str:
    text = str(path)
    return "{" + text.replace("}", "\\}") + "}"


def discover_designs(results_root: Path, variant: str) -> list[str]:
    designs = []
    for child in sorted(results_root.iterdir()):
        if child.is_dir() and (child / variant).is_dir():
            designs.append(child.name)
    return designs


def run_openroad(openroad: str, tcl: str, log: Path) -> bool:
    log.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", suffix=".tcl", delete=False, encoding="utf-8") as f:
        f.write(tcl)
        tcl_path = Path(f.name)
    try:
        proc = subprocess.run(
            [openroad, "-no_init", "-no_splash", str(tcl_path)],
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
        )
        log.write_text(proc.stdout, encoding="utf-8", errors="ignore")
        return proc.returncode == 0
    finally:
        tcl_path.unlink(missing_ok=True)


def report_check_options(group_path_count: int, endpoint_path_count: int) -> str:
    return (
        f"-group_path_count {group_path_count} \\\n"
        f"  -endpoint_path_count {endpoint_path_count} \\\n"
        "  -unique_paths_to_endpoint"
    )


def endpoint_report_tcl(json_dir_name: str, rpt_name: str, summary_name: str) -> str:
    return f"""
proc write_all_endpoint_timing_reports {{out_dir}} {{
  set json_dir "$out_dir/{json_dir_name}"
  file delete -force $json_dir
  file mkdir $json_dir

  set rpt_file "$out_dir/{rpt_name}"
  set fp [open $rpt_file w]
  puts $fp "# Endpoint-complete timing report."
  puts $fp "# Generated by enumerating all_registers -data_pins and all_outputs."
  close $fp

  set endpoint_list "$out_dir/{json_dir_name}_endpoints.txt"
  set efp [open $endpoint_list w]
  array set seen {{}}
  set endpoints {{}}
  foreach endpoint [concat [all_registers -data_pins] [all_outputs]] {{
    set endpoint_name [get_full_name $endpoint]
    if {{![info exists seen($endpoint_name)]}} {{
      set seen($endpoint_name) 1
      lappend endpoints $endpoint
      puts $efp $endpoint_name
    }}
  }}
  close $efp

  set idx 0
  foreach endpoint $endpoints {{
    set endpoint_name [get_full_name $endpoint]
    foreach delay {{max min}} {{
      set json_file "$json_dir/[format {{endpoint_%06d_%s.json}} $idx $delay]"
      set afp [open $rpt_file a]
      puts $afp ""
      puts $afp "=========================================================================="
      puts $afp "endpoint $idx $delay $endpoint_name"
      puts $afp "--------------------------------------------------------------------------"
      close $afp
      catch {{
        report_checks -path_delay $delay -to $endpoint -format full_clock_expanded \\
          -fields {{input_pin slew capacitance net}} -endpoint_path_count 1 >> $rpt_file
      }} rpt_err
      catch {{
        report_checks -path_delay $delay -to $endpoint -format json \\
          -endpoint_path_count 1 > $json_file
      }} json_err
    }}
    incr idx
  }}

  set sfp [open "$out_dir/{summary_name}" w]
  puts $sfp "{{"
  puts $sfp "  \\"endpoint_count\\": [llength $endpoints],"
  puts $sfp "  \\"path_delays\\": [list \\"max\\" \\"min\\"],"
  puts $sfp "  \\"source\\": \\"all_registers -data_pins + all_outputs\\""
  puts $sfp "}}"
  close $sfp
}}
"""


def final_report_tcl(
    flow_root: Path,
    platform: str,
    design: str,
    variant: str,
    group_path_count: int,
    endpoint_path_count: int,
    results_dir: Path | None = None,
    reports_dir: Path | None = None,
    objects_dir: Path | None = None,
) -> str:
    results_dir = results_dir or flow_root / "flow" / "results" / platform / design / variant
    reports_dir = reports_dir or flow_root / "flow" / "reports" / platform / design / variant / "ml_reports"
    platform_dir = flow_root / "flow" / "platforms" / platform
    lib_file = liberty_file(flow_root, platform, design, variant, objects_dir)
    setrc = platform_dir / "setRC.tcl"
    voltage = platform_nominal_voltage(platform)
    return f"""
set results_dir {tcl_quote(results_dir)}
set out_dir {tcl_quote(reports_dir)}
file mkdir $out_dir

read_liberty {tcl_quote(lib_file)}
read_db $results_dir/6_final.odb

if {{[file exists $results_dir/6_final.sdc]}} {{
  read_sdc $results_dir/6_final.sdc
}} elseif {{[file exists $results_dir/5_route.sdc]}} {{
  read_sdc $results_dir/5_route.sdc
}}

if {{[file exists {setrc}]}} {{
  source {tcl_quote(setrc)}
}}

if {{[file exists $results_dir/6_final.spef]}} {{
  read_spef $results_dir/6_final.spef
}}

catch {{ set_propagated_clock [all_clocks] }}
catch {{ set_power_activity -input -activity 0.1 }}
catch {{ set_power_activity -input_port reset -activity 0 }}

{endpoint_report_tcl("path_report_endpoint_json", "path_report.rpt", "endpoint_report_summary.json")}
write_all_endpoint_timing_reports $out_dir

report_checks -unconstrained -format full_clock_expanded \\
  -fields {{input_pin slew capacitance net}} \\
  {report_check_options(group_path_count, endpoint_path_count)} > $out_dir/path_report_unconstrained.rpt

	report_power -digits 6 > $out_dir/power.rpt
	report_power -instances [get_cells *] -digits 6 > $out_dir/instance_power.rpt
	catch {{ check_drc -output_file $out_dir/drc.rpt }} drc_error
	if {{[info exists drc_error] && $drc_error ne ""}} {{
	  set fp [open "$out_dir/drc.log" w]
	  puts $fp $drc_error
	  close $fp
	}}
	catch {{
	  set_pdnsim_net_voltage -net VDD -voltage {voltage}
	  analyze_power_grid -net VDD -source_type STRAPS \\
	    -error_file $out_dir/ir_drop_VDD.rpt \\
	    -voltage_file $out_dir/ir_drop_VDD.csv
	}} ir_vdd_error
	if {{[info exists ir_vdd_error] && $ir_vdd_error ne ""}} {{
	  set fp [open "$out_dir/ir_drop_VDD.log" w]
	  puts $fp $ir_vdd_error
	  close $fp
	}}
	catch {{
	  set_pdnsim_net_voltage -net VSS -voltage 0.0
	  analyze_power_grid -net VSS -source_type STRAPS \\
	    -error_file $out_dir/ir_drop_VSS.rpt \\
	    -voltage_file $out_dir/ir_drop_VSS.csv
	}} ir_vss_error
	if {{[info exists ir_vss_error] && $ir_vss_error ne ""}} {{
	  set fp [open "$out_dir/ir_drop_VSS.log" w]
	  puts $fp $ir_vss_error
	  close $fp
	}}
	report_wns > $out_dir/wns.rpt
report_tns > $out_dir/tns.rpt
report_design_area > $out_dir/design_area.rpt
exit
"""


def parse_spef_caps(spef_path: Path) -> dict[str, float]:
    if not spef_path.exists():
        return {}
    text = spef_path.read_text(encoding="utf-8", errors="ignore")
    name_map: dict[str, str] = {}
    in_name_map = False
    for line in text.splitlines():
        if line.startswith("*NAME_MAP"):
            in_name_map = True
            continue
        if in_name_map and line.startswith("*") and not re.match(r"\*\d+\s+", line):
            in_name_map = False
        if in_name_map:
            match = re.match(r"\*(\d+)\s+(.+)", line)
            if match:
                name_map[f"*{match.group(1)}"] = match.group(2).strip()
    caps: dict[str, float] = {}
    for match in re.finditer(r"(?m)^\*D_NET\s+(\S+)\s+([-+eE.\d]+)", text):
        raw_name, cap = match.group(1), float(match.group(2))
        caps[name_map.get(raw_name, raw_name)] = cap
    return caps


def read_clock_period_ps(results_dir: Path) -> float | None:
    path = results_dir / "clock_period.txt"
    if not path.exists():
        return None
    try:
        return float(path.read_text(encoding="utf-8", errors="ignore").strip())
    except ValueError:
        return None


def write_estimated_net_power(
    flow_root: Path,
    platform: str,
    design: str,
    variant: str,
    activity: float,
    results_dir: Path | None = None,
    reports_dir: Path | None = None,
) -> None:
    results_dir = results_dir or flow_root / "flow" / "results" / platform / design / variant
    reports_dir = reports_dir or flow_root / "flow" / "reports" / platform / design / variant / "ml_reports"
    reports_dir.mkdir(parents=True, exist_ok=True)
    caps_pf = parse_spef_caps(results_dir / "6_final.spef")
    period_ps = read_clock_period_ps(results_dir)
    voltage = platform_nominal_voltage(platform)
    out = reports_dir / "net_power.csv"
    lines = ["net,capacitance_pf,activity,voltage_v,frequency_hz,switching_power_w,source"]
    if period_ps and period_ps > 0:
        frequency_hz = 1.0 / (period_ps * 1e-12)
        for net, cap_pf in sorted(caps_pf.items()):
            power = cap_pf * 1e-12 * voltage * voltage * frequency_hz * activity
            lines.append(f"{net},{cap_pf},{activity},{voltage},{frequency_hz},{power},estimated_from_spef_activity")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


def copy_route_drc_report(
    flow_root: Path,
    platform: str,
    design: str,
    variant: str,
    reports_parent: Path | None = None,
    reports_dir: Path | None = None,
) -> None:
    reports_parent = reports_parent or flow_root / "flow" / "reports" / platform / design / variant
    reports_dir = reports_dir or reports_parent / "ml_reports"
    src = reports_parent / "5_route_drc.rpt"
    dst = reports_dir / "drc.rpt"
    if src.exists():
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(src.read_text(encoding="utf-8", errors="ignore"), encoding="utf-8")


def congestion_report_tcl(
    flow_root: Path,
    platform: str,
    design: str,
    variant: str,
    group_path_count: int,
    endpoint_path_count: int,
    results_dir: Path | None = None,
    reports_dir: Path | None = None,
    objects_dir: Path | None = None,
) -> str:
    results_dir = results_dir or flow_root / "flow" / "results" / platform / design / variant
    reports_dir = reports_dir or flow_root / "flow" / "reports" / platform / design / variant / "ml_reports"
    platform_dir = flow_root / "flow" / "platforms" / platform
    lib_file = liberty_file(flow_root, platform, design, variant, objects_dir)
    fastroute = platform_dir / "fastroute.tcl"
    setrc = platform_dir / "setRC.tcl"
    min_layer, min_clk_layer, max_layer = routing_layers(platform)
    return f"""
set results_dir {tcl_quote(results_dir)}
set out_dir {tcl_quote(reports_dir)}
file mkdir $out_dir

set ::env(MIN_ROUTING_LAYER) {min_layer}
set ::env(MIN_CLK_ROUTING_LAYER) {min_clk_layer}
set ::env(MAX_ROUTING_LAYER) {max_layer}
set ::env(ROUTING_LAYER_ADJUSTMENT) 0.3

read_liberty {tcl_quote(lib_file)}
read_db $results_dir/4_cts.odb
read_sdc $results_dir/4_cts.sdc

if {{[file exists {setrc}]}} {{
  source {tcl_quote(setrc)}
}}

source {tcl_quote(fastroute)}
pin_access -bottom_routing_layer $::env(MIN_ROUTING_LAYER) \\
  -top_routing_layer $::env(MAX_ROUTING_LAYER)

global_route -congestion_report_file $out_dir/congestion.rpt -allow_congestion
if {{![file exists $out_dir/congestion.rpt]}} {{
  set fp [open $out_dir/congestion.rpt w]
  puts $fp "# OpenROAD did not emit a congestion DRC-viewer report for this design."
  puts $fp "# This usually means no reportable global-route congestion was produced."
  close $fp
}}
estimate_parasitics -global_routing

{endpoint_report_tcl("grt_path_report_endpoint_json", "grt_path_report.rpt", "grt_endpoint_report_summary.json")}
write_all_endpoint_timing_reports $out_dir
exit
"""


def has_required_files(
    flow_root: Path, platform: str, design: str, variant: str, stage: str, results_dir: Path | None = None
) -> bool:
    results_dir = results_dir or flow_root / "flow" / "results" / platform / design / variant
    if stage == "final":
        return (results_dir / "6_final.odb").exists()
    return (results_dir / "4_cts.odb").exists() and (results_dir / "4_cts.sdc").exists()


def combine_endpoint_reports(reports_dir: Path, json_dir_name: str, output_json_name: str, summary_name: str) -> None:
    json_dir = reports_dir / json_dir_name
    endpoint_file = reports_dir / f"{json_dir_name}_endpoints.txt"
    if not json_dir.exists():
        return
    checks = []
    seen = set()
    for path in sorted(json_dir.glob("endpoint_*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8", errors="ignore"))
        except json.JSONDecodeError:
            continue
        for check in data.get("checks", []):
            key = (
                check.get("path_type"),
                check.get("startpoint"),
                check.get("endpoint"),
                check.get("slack"),
                check.get("arrival_time"),
            )
            if key in seen:
                continue
            seen.add(key)
            checks.append(check)
    endpoints = []
    if endpoint_file.exists():
        endpoints = [line.strip() for line in endpoint_file.read_text(encoding="utf-8", errors="ignore").splitlines() if line.strip()]
    reported = {check.get("endpoint") for check in checks if check.get("endpoint")}
    missing = sorted(set(endpoints) - reported)
    for endpoint in missing:
        checks.append(
            {
                "type": "endpoint",
                "path_group": "unconstrained",
                "path_type": "unconstrained",
                "startpoint": "",
                "endpoint": endpoint,
                "source_clock": "",
                "source_path": [],
                "target_clock": "",
                "target_clock_path": [],
                "slack": None,
                "required_time": None,
                "endpoint_has_timing_path": False,
            }
        )
    reported = {check.get("endpoint") for check in checks if check.get("endpoint")}
    (reports_dir / output_json_name).write_text(json.dumps({"checks": checks}, indent=2) + "\n", encoding="utf-8")
    summary = {
        "endpoint_count": len(endpoints),
        "reported_endpoint_count": len(reported),
        "missing_endpoint_count": len(set(endpoints) - reported),
        "no_path_endpoint_count": len(missing),
        "check_count": len(checks),
        "json_dir": json_dir_name,
        "output_json": output_json_name,
    }
    existing = reports_dir / summary_name
    if existing.exists():
        try:
            summary = {**json.loads(existing.read_text(encoding="utf-8", errors="ignore")), **summary}
        except json.JSONDecodeError:
            pass
    existing.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate OpenSTA/OpenROAD reports for ML vector extraction.")
    parser.add_argument("--flow-root", default="/home/lyh/OpenROAD-flow-scripts")
    parser.add_argument("--platform", default="nangate45")
    parser.add_argument("--variant", default="base")
    parser.add_argument("--design", action="append", help="Design name. Can be used multiple times. Defaults to all designs.")
    parser.add_argument("--stage", choices=["final", "congestion", "both"], default="both")
    parser.add_argument(
        "--group-path-count",
        type=int,
        default=1_000_000,
        help="Maximum paths per path group. Default is intentionally high to cover endpoints.",
    )
    parser.add_argument(
        "--endpoint-path-count",
        type=int,
        default=1,
        help="Paths per endpoint. Use 1 with -unique_paths_to_endpoint to cover endpoints.",
    )
    parser.add_argument("--openroad", default=DEFAULT_OPENROAD)
    parser.add_argument("--default-activity", type=float, default=DEFAULT_ACTIVITY)
    parser.add_argument("--continue-on-error", action="store_true")
    parser.add_argument("--results-dir", default="", help="External result directory for one design/variant.")
    parser.add_argument("--reports-dir", default="", help="External ml_reports output directory for one design/variant.")
    parser.add_argument("--reports-parent-dir", default="", help="External report directory containing 5_route_drc.rpt.")
    parser.add_argument("--objects-dir", default="", help="External objects directory containing lib/merged.lib.")
    args = parser.parse_args()

    flow_root = Path(args.flow_root).resolve()
    results_dir_arg = Path(args.results_dir).resolve() if args.results_dir else None
    reports_dir_arg = Path(args.reports_dir).resolve() if args.reports_dir else None
    reports_parent_arg = Path(args.reports_parent_dir).resolve() if args.reports_parent_dir else None
    objects_dir_arg = Path(args.objects_dir).resolve() if args.objects_dir else None
    if results_dir_arg and not args.design:
        raise SystemExit("--results-dir requires exactly one --design")
    results_root = flow_root / "flow" / "results" / args.platform
    designs = args.design or discover_designs(results_root, args.variant)
    if results_dir_arg and len(designs) != 1:
        raise SystemExit("--results-dir supports exactly one --design")
    stages = ["final", "congestion"] if args.stage == "both" else [args.stage]

    failures: list[str] = []
    for design in designs:
        for stage in stages:
            reports_dir = reports_dir_arg or flow_root / "flow" / "reports" / args.platform / design / args.variant / "ml_reports"
            reports_parent = reports_parent_arg or reports_dir.parent
            log = reports_dir / f"{stage}.openroad.log"
            if not has_required_files(flow_root, args.platform, design, args.variant, stage, results_dir_arg):
                msg = f"{design}/{args.variant}:{stage}: missing required result files"
                failures.append(msg)
                print(f"[skip] {msg}")
                if not args.continue_on_error:
                    raise SystemExit(1)
                continue
            print(f"[run] {design}/{args.variant}:{stage}")
            tcl = (
                final_report_tcl(
                    flow_root,
                    args.platform,
                    design,
                    args.variant,
                    args.group_path_count,
                    args.endpoint_path_count,
                    results_dir=results_dir_arg,
                    reports_dir=reports_dir,
                    objects_dir=objects_dir_arg,
                )
                if stage == "final"
                else congestion_report_tcl(
                    flow_root,
                    args.platform,
                    design,
                    args.variant,
                    args.group_path_count,
                    args.endpoint_path_count,
                    results_dir=results_dir_arg,
                    reports_dir=reports_dir,
                    objects_dir=objects_dir_arg,
                )
            )
            ok = run_openroad(args.openroad, tcl, log)
            if not ok:
                msg = f"{design}/{args.variant}:{stage}: OpenROAD failed, see {log}"
                failures.append(msg)
                print(f"[fail] {msg}")
                if not args.continue_on_error:
                    raise SystemExit(1)
            elif stage == "final":
                combine_endpoint_reports(
                    reports_dir, "path_report_endpoint_json", "path_report.json", "endpoint_report_summary.json"
                )
                copy_route_drc_report(flow_root, args.platform, design, args.variant, reports_parent, reports_dir)
                write_estimated_net_power(
                    flow_root, args.platform, design, args.variant, args.default_activity, results_dir_arg, reports_dir
                )
            else:
                combine_endpoint_reports(
                    reports_dir, "grt_path_report_endpoint_json", "grt_path_report.json", "grt_endpoint_report_summary.json"
                )

    if failures:
        print("\nFailures:")
        for item in failures:
            print(f"  {item}")
        raise SystemExit(1)


if __name__ == "__main__":
    main()
