#!/usr/bin/env python3
"""Generate timing, power, and congestion reports for ORFS ML parsing.

Reports are written to:

  flow/reports/<platform>/<design>/<variant>/ml_reports/

This script intentionally uses plain OpenROAD Tcl so it can run on already
completed ORFS result directories without re-entering the full Make flow.

Strict stage isolation (CTS -> route timing prediction dataset):
  - place stage: read_db 3_place.odb + 3_place.sdc, propagated clock,
    estimate_parasitics -placement ONLY. No global_route, no GRT parasitics,
    no SPEF, no GRT congestion -- nothing produced downstream of placement.
  - cts stage:   read_db 4_cts.odb + 4_cts.sdc, propagated clock (real CTS
    tree), estimate_parasitics -placement ONLY. No GRT/SPEF leakage.
  - route stage: read_db 6_final.odb + 6_final.sdc + read_spef 6_final.spef
    (the label side; post-route information is allowed here).

Each stage additionally dumps:
  <prefix>net_timing.csv   per driver->sink arc, rise/fall x min/max delay+slew
  <prefix>net_cap.csv      per net capacitance (pF semantics, Farads dumped)
  <prefix>pin_timing.csv   per pin arrival/slack/slew4/required(+valid)/location
  <prefix>design_info.csv  die/core area, clock periods (Tcl side)
and Python-side <prefix>design_info.json (PVT, routing constraints, WNS/TNS,
stage-boundary metadata such as parasitic_source / routing_information_used).
"""
