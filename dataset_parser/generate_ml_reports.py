def copy_route_congestion_report(
    flow_root: Path,
    platform: str,
    design: str,
    variant: str,
    reports_parent: Path | None = None,
    reports_dir: Path | None = None,
) -> None:
    """Route-stage GRT congestion map (written by ORFS global_route.tcl during
    5_route) into ml_reports/congestion.rpt for the route stage only.

    Pre-routing stages (place/cts) never see this file: their report generation
    runs on 3_place.odb / 4_cts.odb without global_route, so no congestion
    report exists in their ml_reports and their vectors keep congestion=null.
    """
    reports_parent = reports_parent or flow_root / "flow" / "reports" / platform / design / variant
    reports_dir = reports_dir or reports_parent / "ml_reports"
    src = reports_parent / "congestion.rpt"
    dst = reports_dir / "congestion.rpt"
    dst.parent.mkdir(parents=True, exist_ok=True)
    if src.exists():
        dst.write_text(src.read_text(encoding="utf-8", errors="ignore"), encoding="utf-8")
    else:
        # GRT only writes the DRC-viewer congestion report when overflowed GRC
        # edges exist. A finished route with no congestion.rpt means the design
        # routed with zero overflow - record that explicitly so the route
        # vectors get congestion_available=true with an empty marker list.
        dst.write_text(
            "# OpenROAD did not emit a congestion DRC-viewer report for this design.\n"
            "# This usually means no reportable global-route congestion was produced.\n",
            encoding="utf-8",
        )


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate OpenSTA/OpenROAD reports for ML vector extraction.")
    parser.add_argument("--flow-root", default="/home/lyh/OpenROAD-flow-scripts")
    parser.add_argument("--platform", default="nangate45")
    parser.add_argument("--variant", default="base")
    parser.add_argument("--design", action="append", help="Design name. Can be used multiple times. Defaults to all designs.")
    parser.add_argument("--stage", choices=["final", "congestion", "place", "both", "all"], default="all")
    parser.add_argument(
        "--group-path-count",
        type=int,
        default=1_000_000,
        help="Maximum paths per path group. Default is intentionally high to cover endpoints.",
    )
    parser.add_argument(
        "--endpoint-path-count",
        type=int,
        default=1,
        help="Paths per endpoint. Use 1 with -unique_paths_to_endpoint to cover endpoints.",
    )
    parser.add_argument("--openroad", default=DEFAULT_OPENROAD)
    parser.add_argument("--default-activity", type=float, default=DEFAULT_ACTIVITY)
    parser.add_argument("--continue-on-error", action="store_true")
    parser.add_argument("--results-dir", default="", help="External result directory for one design/variant.")
    parser.add_argument("--reports-dir", default="", help="External ml_reports output directory for one design/variant.")
    parser.add_argument("--reports-parent-dir", default="", help="External report directory containing 5_route_drc.rpt.")
    parser.add_argument("--objects-dir", default="", help="External objects directory containing lib/merged.lib.")
    args = parser.parse_args()

    flow_root = Path(args.flow_root).resolve()
    results_dir_arg = Path(args.results_dir).resolve() if args.results_dir else None
    reports_dir_arg = Path(args.reports_dir).resolve() if args.reports_dir else None
    reports_parent_arg = Path(args.reports_parent_dir).resolve() if args.reports_parent_dir else None
    objects_dir_arg = Path(args.objects_dir).resolve() if args.objects_dir else None
    if results_dir_arg and not args.design:
        raise SystemExit("--results-dir requires exactly one --design")
    results_root = flow_root / "flow" / "results" / args.platform
    designs = args.design or discover_designs(results_root, args.variant)
    if results_dir_arg and len(designs) != 1:
        raise SystemExit("--results-dir supports exactly one --design")
    stages = {
        "both": ["final", "congestion"],
        "all": ["place", "congestion", "final"],
    }.get(args.stage, [args.stage])

    failures: list[str] = []
    for design in designs:
        lib_file = liberty_file(flow_root, args.platform, design, args.variant, objects_dir_arg)
        for stage in stages:
            reports_dir = (
                reports_dir_arg
                or flow_root / "flow" / "reports" / args.platform / design / args.variant / "ml_reports"
            )
            reports_parent = reports_parent_arg or reports_dir.parent
            log = reports_dir / f"{stage}.openroad.log"
            if not has_required_files(flow_root, args.platform, design, args.variant, stage, results_dir_arg):
                msg = f"{design}/{args.variant}:{stage}: missing required result files"
                failures.append(msg)
                print(f"[skip] {msg}")
                if not args.continue_on_error:
                    raise SystemExit(1)
                continue
            print(f"[run] {design}/{args.variant}:{stage}")
            report_tcl_fns = {
                "final": final_report_tcl,
                "congestion": congestion_report_tcl,
                "place": place_report_tcl,
            }
            tcl = report_tcl_fns[stage](
                flow_root,
                args.platform,
                design,
                args.variant,
                args.group_path_count,
                args.endpoint_path_count,
                results_dir=results_dir_arg,
                reports_dir=reports_dir,
                objects_dir=objects_dir_arg,
            )
            ok = run_openroad(args.openroad, tcl, log)
            if not ok:
                msg = f"{design}/{args.variant}:{stage}: OpenROAD failed, see {log}"
                failures.append(msg)
                print(f"[fail] {msg}")
                if not args.continue_on_error:
                    raise SystemExit(1)
            elif stage == "final":
                combine_endpoint_reports(
                    reports_dir, "path_report_endpoint_json", "path_report.json", "endpoint_report_summary.json"
                )
                copy_route_drc_report(flow_root, args.platform, design, args.variant, reports_parent, reports_dir)
                copy_route_congestion_report(flow_root, args.platform, design, args.variant, reports_parent, reports_dir)
                write_estimated_net_power(
                    flow_root, args.platform, design, args.variant, args.default_activity, results_dir_arg, reports_dir
                )
            elif stage == "place":
                combine_endpoint_reports(
                    reports_dir,
                    "place_grt_path_report_endpoint_json",
                    "place_grt_path_report.json",
                    "place_grt_endpoint_report_summary.json",
                )
            else:
                combine_endpoint_reports(
                    reports_dir, "grt_path_report_endpoint_json", "grt_path_report.json", "grt_endpoint_report_summary.json"
                )
            combined_name = {
                "final": "path_report.json",
                "place": "place_grt_path_report.json",
                "congestion": "grt_path_report.json",
            }[stage]
            write_stage_design_info(
                reports_dir,
                "route" if stage == "final" else ("place" if stage == "place" else "cts"),
                args.platform,
                design,
                args.variant,
                lib_file,
                combined_name,
            )

    if failures:
        print("\nFailures:")
        for item in failures:
            print(f"  {item}")
        raise SystemExit(1)


if __name__ == "__main__":
    main()
